const puppeteer = require('puppeteer');
const fs = require('fs');
const path = require('path');

async function scrapeCookies(url) {
  console.log(`Launching headless browser for ${url}`);
        const browser = await puppeteer.launch({
                headless: 'new', args: [
                        '--no-sandbox',
                        '--disable-setuid-sandbox',
                        '--disable-dev-shm-usage',
                        '--disable-gpu',
                        '--disable-web-security',
                        '--disable-features=VizDisplayCompositor'
                ] }); // Run in headless mode
  const page = await browser.newPage();

  try {
    // Set longer timeouts
    page.setDefaultTimeout(60000); // 60 seconds
    page.setDefaultNavigationTimeout(60000);

    console.log(`Navigating to ${url}`);
    await page.goto(url, { waitUntil: 'networkidle2', timeout: 60000 });

    // Wait for page to load and set cookies - longer wait for YouTube
    console.log('Waiting for page to load and set cookies...');
    await new Promise(resolve => setTimeout(resolve, 10000)); // Wait 10 seconds for cookies to be set

    // For YouTube specifically, try to trigger cookie setting
    if (url.includes('youtube.com') || url.includes('youtu.be')) {
      console.log('Detected YouTube URL, performing additional interactions...');
      
      // Try to scroll a bit to trigger lazy loading
      await page.evaluate(() => {
        window.scrollTo(0, 500);
      });
      await new Promise(resolve => setTimeout(resolve, 3000));

      // Try to click on video area if present
      try {
        await page.waitForSelector('video, .html5-video-container', { timeout: 5000 });
        await page.click('video, .html5-video-container');
        console.log('Clicked on video element');
        await new Promise(resolve => setTimeout(resolve, 2000));
      } catch (e) {
        console.log('Video element not found or clickable, continuing...');
      }
    }

    // Perform some basic interactions to trigger cookie setting
    try {
      // Try to click on something that might trigger cookie consent or login prompts
      await page.mouse.move(100, 100);
      await page.mouse.click(100, 100);
      await new Promise(resolve => setTimeout(resolve, 2000));
    } catch (e) {
      console.log('Interaction failed, continuing...');
    }

    // Ensure page is still open before getting cookies
    if (page.isClosed()) {
      throw new Error('Page was closed unexpectedly');
    }

    // Get cookies
    const cookies = await page.cookies();

    if (cookies.length === 0) {
      console.log('No cookies found');
      return;
    }

    console.log(`Found ${cookies.length} cookies`);

    // Convert to Netscape format
    const netscapeCookies = cookiesToNetscape(cookies, url);

    // Save to file
    const cookiesPath = path.join(__dirname, 'cookies.txt');
    fs.writeFileSync(cookiesPath, netscapeCookies);

    console.log(`Cookies saved to ${cookiesPath} (${cookies.length} cookies)`);

  } catch (error) {
    console.error(`Error scraping cookies: ${error.message}`);
    throw error; // Re-throw to be caught by caller
  } finally {
    await browser.close();
  }
}

function cookiesToNetscape(cookies, domain) {
  let netscape = '# Netscape HTTP Cookie File\n';
  netscape += '# This file was generated by scrape-cookies.js\n\n';

  cookies.forEach(cookie => {
    let domainStr = cookie.domain;
    let flag = cookie.httpOnly ? 'TRUE' : 'FALSE';
    
    // Fix domain/flag relationship for Netscape format
    // If domain starts with '.', flag must be TRUE
    // If domain doesn't start with '.', flag must be FALSE
    if (domainStr.startsWith('.')) {
      flag = 'TRUE';
    } else {
      flag = 'FALSE';
    }
    
    const secure = cookie.secure ? 'TRUE' : 'FALSE';
    const expiry = cookie.expires === -1 ? '0' : Math.floor(cookie.expires).toString();
    const path = cookie.path || '/';

    netscape += `${domainStr}\t${flag}\t${path}\t${secure}\t${expiry}\t${cookie.name}\t${cookie.value}\n`;
  });

  return netscape;
}

// Get URL from command line argument
const url = process.argv[2] || 'https://www.youtube.com';

scrapeCookies(url).catch(console.error);